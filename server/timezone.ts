/**
 * 서버는 한국 시각으로 생각한다.
 *
 * ⚠ 이 파일은 server/index.ts 에서 **가장 먼저** import 해야 한다.
 * ESM 은 import 를 적힌 순서대로 평가하므로, 다른 모듈이 Date 를 만지기 전에
 * 여기가 먼저 돌아야 한다.
 *
 * 왜 필요한가.
 *
 * TAGO 시각표는 "0536" 처럼 **한국 시각의 벽시계 숫자**로 온다. 그걸
 * Date 로 바꾸는 코드가 setHours/setMinutes 를 쓰는데, 그 메서드들은
 * 프로세스의 지역 시간대를 따른다. 개발 노트북(KST)에서는 맞고,
 * 운영 서버(Etc/UTC)에서는 9시간이 밀린다.
 *
 * 실제로 그랬다 (2026-09-05). 지하철 첫차 05:36 이 오후 2시 36분으로 잡혀서,
 * 목표 시각까지 닿는 편이 하나도 없다고 판단하고 "경로를 찾지 못했습니다" 를
 * 돌려줬다. 로컬에서는 멀쩡했다.
 *
 * 배포 설정(systemd 의 Environment=TZ)으로 고칠 수도 있지만, 그러면 저장소를
 * 옮기거나 다른 데서 띄울 때 같은 함정을 다시 밟는다. 코드에 둔다.
 *
 * 요일 판정(평일/토/일 시각표)과 조회 날짜(YYYYMMDD)도 같은 가정 위에 있어서,
 * 여기 한 줄이 그 전부를 함께 고친다.
 */
process.env.TZ = 'Asia/Seoul'

/** 이 서버가 시각을 해석하는 기준. 테스트가 확인한다. */
export const SERVER_TZ = 'Asia/Seoul'
